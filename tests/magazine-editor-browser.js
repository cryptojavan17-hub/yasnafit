'use strict';
// Opt-in real browser/UI test with a temporary DB and coach-authenticated API.
// Install Playwright separately; no production dependency or real source copy.
const assert = require('node:assert/strict');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path'), net = require('node:net');
const { spawn } = require('node:child_process');
const { DatabaseSync } = require('node:sqlite');
const { chromium } = require('playwright');
const { runMigrations } = require('../src/migrations');
const articles = require('../src/article-service');
const auth = require('../src/coach-auth-service'), totp = require('../src/totp');
const root = path.join(__dirname, '..'), dir = fs.mkdtempSync(path.join(os.tmpdir(), 'yasnafit-editor-'));
const output = path.join(root, 'logs', 'magazine-editor-browser');
const sourceUrl = 'https://fitamin.ir/mag/how-to-reduce-breast-size-naturally/';
const body = '<p>متن آزمایشی مربی؛ این نوشته باید هنگام ویرایش حفظ شود.</p>'.repeat(25);
let server, browser;
(async () => {
  fs.mkdirSync(output, { recursive: true });
  const db = new DatabaseSync(path.join(dir, 'yasnafit.db'));
  runMigrations(db);
  auth.setupCoach(db, { email: 'crypto.javan17@gmail.com', password: 'YasnafitCoach1', displayName: 'مربی آزمایش' });
  const secret = auth.provisionCoachTotp(db).secret;
  const a = articles.createArticle(db, { title: 'ورزش‌های ساده برای کوچک شدن سینه زنان در خانه', content: body, summary: 'متن ساختگی فقط برای آزمون عملکرد ویرایشگر', content_origin: 'imported', category: 'health', source_name: 'فیتامین', source_url: sourceUrl, sources: [{ name: 'فیتامین', url: sourceUrl }], publish: true });
  for (let i = 0; i < 25; i++) articles.createArticle(db, { title: 'مقالهٔ آزمایشی فهرست ' + i, content: '<p>متن آزمایش</p>' });
  const nutritionId = db.prepare("SELECT id FROM magazine_categories WHERE slug='nutrition'").get().id;
  db.close();
  const port = await new Promise(resolve => { const s = net.createServer(); s.listen(0, '127.0.0.1', () => { const p = s.address().port; s.close(() => resolve(p)); }); });
  const base = `http://127.0.0.1:${port}`;
  server = spawn(process.execPath, ['server.js'], { cwd: root, env: { ...process.env, PORT: String(port), YASNAFIT_DATA_DIR: dir }, stdio: 'ignore' });
  let ready = false;
  for (let i = 0; i < 60; i++) { try { if ((await fetch(base + '/api/health')).ok) { ready = true; break; } } catch (_) {} await new Promise(r => setTimeout(r, 200)); }
  assert(ready);
  const login = await fetch(base + '/api/coach/auth/login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: 'crypto.javan17@gmail.com', password: 'YasnafitCoach1' }) });
  const verify = await fetch(base + '/api/coach/auth/verify', { method: 'POST', headers: { 'Content-Type': 'application/json', Cookie: login.headers.get('set-cookie').split(';')[0] }, body: JSON.stringify({ code: totp.generate(secret) }) });
  assert.equal(verify.status, 200);
  const cookie = verify.headers.get('set-cookie').split(';')[0];
  const api = async (url, method = 'GET', data) => { const r = await fetch(base + url, { method, headers: { Cookie: cookie, 'Content-Type': 'application/json' }, body: data === undefined ? undefined : JSON.stringify(data) }); return { status: r.status, data: await r.json() }; };
  browser = await chromium.launch({ executablePath: process.env.YASNAFIT_BROWSER_EXECUTABLE || undefined, headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] });
  const context = await browser.newContext({ viewport: { width: 1360, height: 900 } });
  const eq = cookie.indexOf('=');
  await context.addCookies([{ name: cookie.slice(0, eq), value: cookie.slice(eq + 1), url: base }]);
  // Verify the navigation destination without depending on publisher availability.
  await context.route(sourceUrl, route => route.fulfill({ contentType: 'text/html', body: '<h1>Source navigation fixture</h1>' }));
  const page = await context.newPage(), errors = [], mutations = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => { if (['POST', 'PUT', 'DELETE'].includes(r.method()) && r.url().includes('/api/magazine/admin/articles')) mutations.push({ method: r.method(), url: r.url() }); });
  await page.goto(base + '/coach/magazine');
  const source = page.locator(`[data-article-source="${a.id}"]`);
  await source.waitFor(); assert.equal(await source.getAttribute('href'), sourceUrl);
  const popupPromise = page.waitForEvent('popup'); await source.click(); const popup = await popupPromise;
  await popup.waitForLoadState(); assert.equal(popup.url(), sourceUrl); await popup.close();
  console.log('PASS coach View opens original source in a new tab');
  const edit = page.locator(`[data-action="edit"][data-id="${a.id}"]`);
  await edit.scrollIntoViewIfNeeded(); const scrollBefore = await page.evaluate(() => window.scrollY);
  assert(scrollBefore > 0);
  await edit.click();
  const dialog = page.locator('.mag-article-dialog');
  await dialog.locator('[name="content"]').waitFor();
  assert.equal(await dialog.locator('[name="content"]').inputValue(), body);
  assert.equal(await dialog.locator('[data-source-field="name"]').inputValue(), 'فیتامین');
  const box = await dialog.boundingBox();
  assert(box.y >= 0 && box.y < 90 && box.y + box.height <= 900 && box.x >= 0 && box.x + box.width <= 1360);
  assert.equal(await page.evaluate(() => document.activeElement.name), 'title');
  assert.equal(await page.evaluate(() => getComputedStyle(document.body).overflow), 'hidden');
  await dialog.locator('.modal-body').evaluate(el => { el.scrollTop = el.scrollHeight; });
  const save = dialog.locator('[type="submit"]'); const saveBox = await save.boundingBox(); assert(saveBox.y >= 0 && saveBox.y + saveBox.height < 900);
  await dialog.locator('.modal-body').evaluate(el => { el.scrollTop = 0; });
  await page.screenshot({ path: path.join(output, 'desktop-editor.png') });
  await dialog.locator('[name="title"]').fill('عنوان ویرایش‌شدهٔ مقاله');
  await dialog.locator('[name="category"]').selectOption(String(nutritionId));
  const endpoint = base + `/api/magazine/admin/articles/${a.id}`;
  const failSave = route => route.request().method() === 'PUT' ? route.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ error: 'خطای آزمایشی ذخیره' }) }) : route.continue();
  await page.route(endpoint, failSave); await save.click();
  await dialog.locator('[data-editor-error]:not([hidden])').waitFor();
  assert.equal(await dialog.locator('[name="content"]').inputValue(), body);
  assert(await save.isEnabled());
  await page.unroute(endpoint, failSave);
  const beforeSave = mutations.length;
  await save.click(); await dialog.waitFor({ state: 'detached' });
  assert.equal(mutations.length - beforeSave, 1);
  const saved = (await api(`/api/magazine/admin/articles/${a.id}`)).data;
  assert.equal(saved.content, body); assert.equal(saved.category_id, nutritionId); assert.equal(saved.content_origin, 'imported'); assert.equal(saved.sources.length, 1);
  console.log('PASS desktop upper-center dialog, scrollable body, fixed actions, full detail/sources, failed-save recovery, persisted edits');
  await page.locator(`[data-action="edit"][data-id="${a.id}"]`).click(); await dialog.locator('[name="content"]').waitFor();
  await page.keyboard.press('Escape'); await dialog.waitFor({ state: 'detached' });
  await page.waitForFunction(() => !document.body.classList.contains('mag-article-editor-open'));
  await page.waitForFunction(() => document.activeElement.dataset.action === 'edit');
  assert.equal(await page.evaluate(() => document.activeElement.dataset.action), 'edit');
  await page.route(endpoint, route => route.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ error: 'خطای آزمایشی دریافت مقاله' }) }));
  await page.locator(`[data-action="edit"][data-id="${a.id}"]`).click();
  await dialog.locator('[role="alert"]').waitFor();
  assert.equal(await dialog.locator('form').count(), 0); // Never offer a blank editor after failed detail fetch.
  await dialog.locator('[data-close-modal]').click(); await dialog.waitFor({ state: 'detached' });
  await page.unroute(endpoint);
  await page.locator('[data-action="view"]').first().click();
  await dialog.locator('.article-body-preview').waitFor();
  assert.equal(await dialog.locator('[type="submit"]').count(), 0);
  await page.mouse.click(1, 1); await dialog.waitFor({ state: 'detached' });
  console.log('PASS failed detail fetch cannot overwrite body; source-less local preview and outside close work');
  page.once('dialog', d => d.dismiss());
  await page.locator(`[data-action="to-draft"][data-id="${a.id}"]`).click();
  assert.equal((await api(`/api/magazine/admin/articles/${a.id}`)).data.status, 'PUBLISHED');
  page.once('dialog', d => d.accept());
  await page.locator(`[data-action="to-draft"][data-id="${a.id}"]`).click();
  await page.locator(`[data-action="publish"][data-id="${a.id}"]`).waitFor();
  assert.equal((await api(`/api/magazine/admin/articles/${a.id}`)).data.status, 'DRAFT');
  assert.equal((await fetch(base + '/magazine/' + encodeURIComponent(a.slug))).status, 404);
  assert.equal((await api(`/api/magazine/admin/articles/${a.id}`)).data.content, body);
  console.log('PASS cancel/unpublish confirmation and actual DRAFT/public-404 transition without data loss');
  await page.locator('[data-tab="news"]').click();
  const queueEdit = page.locator(`[data-news-action="edit"][data-id="${a.id}"]`); await queueEdit.waitFor();
  let detailRequests = 0; const detailCounter = r => { if (r.url() === endpoint && r.method() === 'GET') detailRequests++; }; page.on('request', detailCounter);
  await queueEdit.click(); await dialog.locator('[name="content"]').waitFor();
  assert.equal(await page.locator('.mag-article-dialog').count(), 1); assert.equal(detailRequests, 1);
  await page.keyboard.press('Escape'); await dialog.waitFor({ state: 'detached' }); page.off('request', detailCounter);
  await page.locator('[data-tab="articles"]').click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator(`[data-action="edit"][data-id="${a.id}"]`).click(); await dialog.locator('[name="content"]').waitFor();
  const mobile = await dialog.boundingBox(); assert(mobile.x >= 0 && mobile.x + mobile.width <= 390 && mobile.y >= 0 && mobile.y + mobile.height <= 844);
  assert(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth));
  await page.screenshot({ path: path.join(output, 'mobile-editor.png') });
  await dialog.locator('[name="category"]').selectOption('');
  await dialog.locator('[type="submit"]').click(); await dialog.waitFor({ state: 'detached' });
  assert.equal((await api(`/api/magazine/admin/articles/${a.id}`)).data.category_id, null);
  page.once('dialog', d => d.accept());
  await page.locator(`[data-action="delete"][data-id="${a.id}"]`).click();
  await page.locator(`tr[data-id="${a.id}"]`).waitFor({ state: 'detached' });
  assert.equal((await api(`/api/magazine/admin/articles/${a.id}`)).status, 404);
  console.log('PASS queue edit binds once, mobile dialog stays visible, category cleared, confirmed delete removes article');
  assert.deepEqual(errors, []);
  fs.writeFileSync(path.join(output, 'result.json'), JSON.stringify({ ok: true, desktop: box, mobile, console_page_errors: errors, checks: ['source-navigation', 'full-body-preserved', 'reference-editor', 'category-update-clear', 'save-error-retry', 'single-submit', 'unpublish', 'delete', 'escape-focus', 'single-queue-handler', 'failed-detail-safe', 'source-less-preview', 'outside-close', 'desktop-mobile-bounds'] }, null, 2));
})().catch(e => { console.error(e); process.exitCode = 1; }).finally(async () => {
  if (browser) await browser.close();
  if (server && server.exitCode === null && server.signalCode === null) { const exit = new Promise(r => server.once('exit', r)); server.kill(); await exit; }
  fs.rmSync(dir, { recursive: true, force: true });
});
